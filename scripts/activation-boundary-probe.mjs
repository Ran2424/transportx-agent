// Run with: node --experimental-strip-types scripts/activation-boundary-probe.mjs
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { activation } from '../modules/capabilities/tool-activation/extensions/pi-tool-activation/activation.ts';
import { parseModuleManifestStructured } from '../src/contracts/module.ts';

const root = fileURLToPath(new URL('../modules/capabilities/tool-activation/extensions/pi-tool-activation/', import.meta.url));
const source = path.join(root, 'module-tools.ts'), manager = path.join(root, 'activation.ts');
const input = { type: 'object', properties: {} };
const contract = { moduleId: 'example.any', toolId: 'example.first', piName: 'first', contractVersion: '1.0.0', semanticVersion: 'v1', input, output: { protocol: 'x', version: 1, detailsKind: 'x' } };
const fixture = { id: 'example.any', version: '1', name: 'fixture', description: '', searchText: '', extensions: [source], skills: [], contracts: [contract], initialTools: [{ piName: 'first', contract: 'first.json', sha256: 'a'.repeat(64) }] };
const tools = ['read', 'write', 'edit', 'bash'].map(name => ({ name, sourceInfo: { source: 'builtin', path: `<builtin:${name}>` } }));
tools.push({ name: 'first', parameters: input, sourceInfo: { path: source } }, { name: 'second', parameters: input, sourceInfo: { path: source } }, { name: 'manage_capabilities', parameters: input, sourceInfo: { path: manager } });
let active = [], entries = [];
const pi = { getAllTools: () => tools, setActiveTools: value => { active = value; }, getActiveTools: () => active, appendEntry: (customType, data) => entries.push({ type: 'custom', customType, data }), events: { emit() {} } };
const ctx = { sessionManager: { getBranch: () => entries } };
const managerModule = { id: 'com.transportx.tool-activation', version: '1', name: 'manager', description: '', searchText: '', extensions: [manager], skills: [], contracts: [], initialTools: [] };
let state = activation(pi, [fixture, managerModule]);
state.restore(ctx);
assert.ok(active.includes('first')); assert.ok(!active.includes('second'));
fixture.initialTools = [];
state = activation(pi, [fixture, managerModule]); state.restore(ctx);
assert.ok(active.includes('first'), 'assembly record freezes initial policy');
state.enable(state.rows().find(row => row.module.id === fixture.id), ctx);
assert.ok(active.includes('second')); state.restore(ctx);
assert.ok(active.includes('second'), 'enable is restored');
tools.find(tool => tool.name === 'first').parameters = { type: 'object', properties: { changed: { type: 'string' } } };
state.restore(ctx); assert.ok(!active.includes('first')); assert.ok(!active.includes('second'));
tools.find(tool => tool.name === 'first').parameters = input;
tools.find(tool => tool.name === 'first').sourceInfo.path = manager;
state.restore(ctx); assert.ok(!active.includes('first'), 'tool owned by another extension is rejected');
tools.find(tool => tool.name === 'first').sourceInfo.path = source;
fixture.contracts = []; fixture.initialTools = [{ piName: 'first', contract: 'first.json', sha256: 'a'.repeat(64) }];
state.restore(ctx); assert.ok(!active.includes('first'), 'an initial tool requires its contract');
const manifest = { manifestVersion: 2, id: 'example.any', name: 'Example', version: '1.0.0', type: 'module', platformVersion: '*', dependencies: [], entrypoints: { piExtensions: ['index.ts'] }, contributes: { initialTools: [{ piName: 'first', contract: 'first.json' }] } };
assert.equal(parseModuleManifestStructured(manifest).ok, true);
manifest.contributes.initialTools[0].contract = '../outside.json';
assert.equal(parseModuleManifestStructured(manifest).ok, false);
console.log('Activation probe passed: declaration, frozen policy, enable/resume, schema drift, path rejection');
