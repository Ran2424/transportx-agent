import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { ModuleInstaller } = require('../../bin/module-installer.js');
const { ModuleRegistry } = require('../../bin/module-registry.js');
const { AssetResolver } = require('../../bin/asset-resolver.js');
const { SessionAssembler } = require('../../bin/session-assembly.js');
const { SimulationService } = require('../../bin/simulation-service.js');
const { BUILTIN_MODULE_MANIFESTS } = require('../../bin/config.js');
const { sha256File } = require('../../bin/asset-integrity.js');
const { parseTrafficToolResult } = require('../../bin/contracts/simulation.js');
const { parseCanvasPresentation } = require('../../bin/contracts/canvas.js');
const python = process.env.TAU_PYTHON_COMMAND;
const packageRoot = process.env.TRANSPORTX_SIMULATION_MODULE;
if (!python || !packageRoot) throw new Error('Explicit TAU_PYTHON_COMMAND and TRANSPORTX_SIMULATION_MODULE are required.');
const root = path.resolve(process.argv[2] || 'tmp/simulation-p1-service');
assert.equal(fs.existsSync(root), false, 'Use a new evidence directory'); fs.mkdirSync(root, { recursive: true });
const workspace = path.join(root, 'workspace'), histories = path.join(root, 'histories');
fs.mkdirSync(workspace); fs.mkdirSync(histories);
// Actual installer and assembler: no fabricated Module plan, runtime or engine.
const installer = new ModuleInstaller(path.join(root, 'installed'));
installer.install(path.resolve(packageRoot));
installer.install(path.resolve('modules/optional/hongqiao-night-demo'));
const registry = new ModuleRegistry('3.24.2').load([...BUILTIN_MODULE_MANIFESTS, ...installer.sources()]);
const executable = { command: python, args: [], version: '3.10' };
const assembler = new SessionAssembler(registry, new AssetResolver(registry), '3.24.2', { command: process.execPath, args: [], version: '0.80.10' }, executable);
const plan = assembler.assemble('com.transportx.workbench', workspace);
const sessionFile = path.join(histories, 'probe.jsonl');
fs.writeFileSync(sessionFile, JSON.stringify({ type: 'session', id: 'simulation-service-probe', cwd: workspace }) + '\n');
const session = { id: 'service-probe', workspaceId: 'workspace-probe', cwd: workspace, sessionFile, resolvedSessionPlan: plan };
const notifications = [];
const options = { executable, root: path.join(root, 'executions'), sessionsDirectory: histories, verifyPlan: (value, cwd) => assembler.verify(value, cwd), notify: (_session, run, revision) => notifications.push({ at: Date.now(), state: run.state, runId: run.runId, revision }) };
const service = new SimulationService(options);
const scenario = await service.prepareScenario(session, { assetId: 'data:hongqiao-night-demo', inputPath: 'scenario.json' });
const request = { scenarioId: scenario.scenarioId, toolCallId: 'real-service-run' };
const prepared = service.prepareRun(session, request);
assert.equal(prepared.state, 'prepared');
assert.equal(service.prepareRun(session, request).runId, prepared.runId);
service.bindJob(session, prepared.runId, 'service-probe-job');
assert.throws(() => service.bindJob(session, prepared.runId, 'different-job'), /another Job/);
assert.throws(() => service.prepareRun(session, { ...request, toolCallId: 'replacement' }), /unfinished|unconfirmed/);
const run = await service.run(session, { ...request, operationId: prepared.runId }, new AbortController().signal);
assert.equal(run.state, 'ended', JSON.stringify(run)); assert.equal(run.termination, 'completed');
assert.equal(run.metrics.service.completedJourneys, 2);
assert.equal(run.metrics.service.hubDepartures, 5);
assert.ok(parseTrafficToolResult({ protocol: 'transportx-traffic', version: 1, operation: 'run', run }));
assert.equal(parseTrafficToolResult({ protocol: 'transportx-traffic', version: 1, operation: 'run', run: { ...run, sourceKind: 'invented' } }), null);
assert.ok(parseCanvasPresentation(service.presentation(session, run.runId)));
const frozenContext = service.freezeContext(session, run.runId, { time: 60, objectId: 'bus-0' });
assert.equal(frozenContext.query.time, 60); assert.match(frozenContext.frameSha256, /^[a-f0-9]{64}$/);
const query = service.query(session, { runId: run.runId, time: 60, objectId: 'bus-0' });
assert.equal(query.time, 60); assert.equal(query.vehicle.id, 'bus-0');
assert.ok(Number.isFinite(query.vehicle.lanePositionMeters));
assert.notEqual(query.vehicle.lanePositionMeters, query.vehicle.position[0], 'network XY is not lane distance');
assert.ok(query.events.some((event) => event.type === 'boarded'));
assert.ok(parseTrafficToolResult({ protocol: 'transportx-traffic', version: 1, operation: 'query', run, query }));
assert.ok(service.query(session, { runId: run.runId, time: 60, objectId: 'route:shuttle' }).route.edgeIds.length);
assert.ok(service.query(session, { runId: run.runId, time: 60, objectId: 'route:shuttle' }).events.some((event) => event.type === 'action_rejected'));
assert.ok(service.query(session, { runId: run.runId, time: 60, objectId: 'node:relay' }).events.some((event) => event.type === 'transfer_ready'));
assert.equal(service.geometry(session, run.runId).features.filter((item) => item.geometry.type === 'Point').length, 2);
const restored = new SimulationService(options);
assert.equal(restored.queryExecution(session, { lookupToolCallId: request.toolCallId }).runId, run.runId);
assert.equal(restored.queryExecution(session, { runId: run.runId }).termination, 'completed');
const ownerDirectory = fs.readdirSync(options.root).find((name) => fs.existsSync(path.join(options.root, name, `${run.runId}.json`)));
const runRecord = path.join(options.root, ownerDirectory, `${run.runId}.json`);
const committed = JSON.parse(fs.readFileSync(runRecord, 'utf8'));
const interrupted = { ...committed, state: 'running' };
for (const field of ['termination', 'metrics', 'resultSha256']) delete interrupted[field];
fs.writeFileSync(runRecord, JSON.stringify(interrupted));
const beforeRecovery = fs.readFileSync(runRecord);
const nextHost = new SimulationService(options);
assert.equal(nextHost.list(session).find((item) => item.runId === run.runId).state, 'running');
assert.equal(nextHost.queryExecution(session, { runId: run.runId }).state, 'running');
assert.deepEqual(fs.readFileSync(runRecord), beforeRecovery);
assert.equal(nextHost.recoverExecution(session, { runId: run.runId }).termination, 'completed');
const afterRecovery = fs.readFileSync(runRecord);
const { simulationDigest } = require('../../bin/simulation-job.js');
const reservation = path.join(options.root, 'workspaces', simulationDigest(session.workspaceId) + '.json');
assert.equal(fs.existsSync(reservation), false);
fs.writeFileSync(reservation, JSON.stringify({ owner: committed.owner, runId: run.runId }));
assert.equal(nextHost.recoverExecution(session, { runId: run.runId }).termination, 'completed');
assert.deepEqual(fs.readFileSync(runRecord), afterRecovery);
assert.equal(fs.existsSync(reservation), false);
// Older Hosts could mark an already committed Run unknown while retaining its hash.
fs.writeFileSync(runRecord, JSON.stringify({ ...interrupted, resultSha256: committed.resultSha256 }));
const resultPath = path.join(workspace, 'traffic-simulation/runs', run.runId, 'result.json');
const resultBytes = fs.readFileSync(resultPath);
fs.appendFileSync(resultPath, '\n');
assert.equal(nextHost.recoverExecution(session, { runId: run.runId }).error.code, 'traffic_result_invalid');
assert.equal(fs.existsSync(reservation), true);
fs.writeFileSync(resultPath, resultBytes);
assert.equal(nextHost.recoverExecution(session, { runId: run.runId }).termination, 'completed');
assert.equal(fs.existsSync(reservation), false);
assert.equal((await restored.run(session, { ...request, operationId: run.runId }, new AbortController().signal)).runId, run.runId);
assert.throws(() => restored.queryExecution({ ...session, workspaceId: 'other-workspace' }, { runId: run.runId }), /different workspace/);
assert.throws(() => service.query(session, { runId: run.runId, time: 201 }), /not been published/);
assert.ok(notifications.some((item) => item.state === 'running' && item.revision > 0), 'Index is visible before final confirmation');
const roadScenario = await service.prepareScenario(session, { assetId: 'data:hongqiao-night-demo', inputPath: 'road-scenario.json' });
const road = await service.run(session, { scenarioId: roadScenario.scenarioId, toolCallId: 'pure-road' }, new AbortController().signal);
assert.equal(road.termination, 'completed', JSON.stringify(road)); assert.equal(road.metrics.road.arrived, 3);
assert.equal(road.metrics.service, undefined);
assert.throws(() => service.query(session, { runId: road.runId, time: 60, objectId: 'node:hub' }), /does not exist/);
// Same actual engine, larger but still measured synthetic profile: interrupt only
// after a complete block has been published, rather than cancelling before spawn.
const sample = JSON.parse(fs.readFileSync(path.resolve('modules/optional/hongqiao-night-demo/assets/night-demo/scenario.json'), 'utf8'));
sample.network.path = 'sample-network.net.xml'; sample.configuration.durationSeconds = 600; sample.configuration.backgroundCount = 120;
sample.configuration.service.travelers = Array.from({ length: 100 }, (_, i) => ({ id: `person-${i}`, time: i, mode: i % 2 ? 'ridehail' : 'bus', destination: i % 2 ? 'west' : 'east' }));
fs.copyFileSync(path.resolve('modules/optional/hongqiao-night-demo/assets/night-demo/network.net.xml'), path.join(workspace, sample.network.path));
fs.writeFileSync(path.join(workspace, 'large-example.json'), JSON.stringify(sample));
const large = await service.prepareScenario(session, { inputPath: 'large-example.json' });
const earlyController = new AbortController(), earlyRequest = { scenarioId: large.scenarioId, toolCallId: 'cancel-after-native-start' };
const earlyReference = service.prepareRun(session, earlyRequest);
let earlyIssued = false;
const earlyTimer = setInterval(() => {
  if (fs.existsSync(path.join(workspace, 'traffic-simulation/runs', earlyReference.runId, 'started.json'))) { earlyIssued = true; earlyController.abort(); clearInterval(earlyTimer); }
}, 5);
let earlyCancelled;
try { earlyCancelled = await service.run(session, { ...earlyRequest, operationId: earlyReference.runId }, earlyController.signal); }
finally { clearInterval(earlyTimer); }
assert.equal(earlyIssued, true); assert.equal(earlyCancelled.termination, 'cancelled', JSON.stringify(earlyCancelled));
const cancellation = new AbortController();
let cancellationIssued = false;
const cancelling = new SimulationService({ ...options, notify: (context, summary, revision) => { options.notify(context, summary, revision); if (revision > 0 && summary.state === 'running' && !cancellationIssued) { cancellationIssued = true; cancellation.abort(); } } });
const cancelled = await cancelling.run(session, { scenarioId: large.scenarioId, toolCallId: 'cancel-after-publication' }, cancellation.signal);
assert.equal(cancellationIssued, true); assert.equal(cancelled.termination, 'cancelled', JSON.stringify(cancelled));
assert.ok(cancelling.index(session, cancelled.runId).chunks.length > 0);
let killed = false;
const faulting = new SimulationService({ ...options, notify: (context, summary, revision) => {
  options.notify(context, summary, revision);
  if (revision > 0 && summary.state === 'running' && !killed) {
    const started = JSON.parse(fs.readFileSync(path.join(workspace, 'traffic-simulation/runs', summary.runId, 'started.json'), 'utf8'));
    process.kill(started.sumoPid, 'SIGKILL'); killed = true;
  }
} });
const unknown = await faulting.run(session, { scenarioId: large.scenarioId, toolCallId: 'engine-fault' }, new AbortController().signal);
assert.equal(killed, true); assert.equal(unknown.state, 'unknown');
assert.equal(new SimulationService(options).queryExecution(session, { runId: unknown.runId }).state, 'unknown');
assert.throws(() => faulting.prepareRun(session, { scenarioId: large.scenarioId, toolCallId: 'replacement-after-fault' }), /unfinished|unconfirmed/);
assert.equal((await faulting.run(session, { scenarioId: large.scenarioId, toolCallId: 'engine-fault', operationId: unknown.runId }, new AbortController().signal)).runId, unknown.runId);
const recoveredCancellation = faulting.cancel(session, { runId: unknown.runId });
assert.equal(recoveredCancellation.termination, 'cancelled', 'Explicit cancellation releases an unknown Run only after OS-confirmed stop');
const neverDispatched = faulting.prepareRun(session, { scenarioId: large.scenarioId, toolCallId: 'explicit-new-after-recovery' });
assert.equal(faulting.cancel(session, { runId: neverDispatched.runId }).termination, 'cancelled');
assert.equal(fs.existsSync(path.join(workspace, 'traffic-simulation/runs', neverDispatched.runId, 'started.json')), false);
installer.uninstall('com.transportx.hongqiao-night-demo', registry);
installer.uninstall('com.transportx.traffic-simulation');
const historical = new SimulationService(options);
assert.equal(historical.queryExecution(session, { runId: run.runId }).termination, 'completed');
assert.equal(historical.query(session, { runId: run.runId, time: 60, objectId: 'bus-0' }).vehicle.id, 'bus-0');
const indexPath = path.join(workspace, 'traffic-simulation/runs', run.runId, 'index.json'), originalIndex = fs.readFileSync(indexPath);
fs.writeFileSync(indexPath, originalIndex.toString() + ' ');
assert.throws(() => historical.index(session, run.runId), /Committed result index changed/);
fs.writeFileSync(indexPath, originalIndex);
const evidence = { protocol: 'transportx-simulation-service-probe', version: 1, scope: 'actual installer/assembler/Host service/Python/SUMO, early and post-publication cancellation, engine kill, explicit recovery, historical read after uninstall and committed-index tampering; Pi RPC, native trust UI and Canvas acceptance are separate', scenario, run, road, query, earlyCancelled, cancelled, unknown, recoveredCancellation, notifications, packageManifestSha256: sha256File(path.join(path.resolve(packageRoot), 'manifest.json')), output: path.join(workspace, 'traffic-simulation/runs', run.runId) };
fs.writeFileSync(path.join(root, 'evidence.json'), JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify({ evidence: path.join(root, 'evidence.json'), termination: run.termination, actualCompletedJourneys: run.metrics.service.completedJourneys }));
