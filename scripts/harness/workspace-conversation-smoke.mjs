#!/usr/bin/env node
// Isolated real Host + fake Pi + Chrome verification of the durable conversation API.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(path.join(process.cwd(), 'package.json'));
const { chromium } = require('playwright');
const { WebSocket } = require('ws');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tau-new-api-smoke-'));
const scenario = path.join(root, 'events.json');
fs.writeFileSync(scenario, JSON.stringify({ fallback: { steps: [{ delay: 5000 }, { streamText: { text: '新会话完成', chunks: 1 } }] } }));
const host = spawn(process.execPath, ['scripts/harness/serve-with-fake-pi.mjs', '--scenario', scenario], { cwd: process.cwd(), env: process.env, stdio: ['ignore', 'pipe', 'pipe'] });
let log = '', errors = '', browser;
host.stdout.on('data', b => log += b);
host.stderr.on('data', b => errors += b);
try {
    const started = Date.now();
    while (!log.includes('TAU_FAKE_READY ')) {
        if (host.exitCode !== null || Date.now() - started > 15000)
            throw Error(log + errors);
        await new Promise(r => setTimeout(r, 50));
    }
    const ready = JSON.parse(log.match(/TAU_FAKE_READY (\{[^\n]+\})/)[1]);
    const base = ready.baseUrl;
    const req = async (url, body, method = body === undefined ? 'GET' : 'POST', protocol = true) => { const response = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json', ...(protocol ? { 'X-TransportX-Protocol': '2' } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); let data; try {
        data = await response.json();
    }
    catch { } return { status: response.status, data }; };
    let health = await req('/api/health');
    assert.equal(health.data.protocolVersion, 2);
    assert.equal(health.data.dataState, 'ready');
    assert.equal((await req('/api/live-sessions', {}, 'POST', false)).status, 426);
    assert.equal((await req('/api/live-sessions', {})).status, 404);
    const profile = { schemaVersion: 1, task: { kind: 'data-query', expectedOutputs: ['answer'] }, modules: { selectionMode: 'explicit', selected: [] } };
    const input = { requestId: crypto.randomUUID(), workspace: { kind: 'new', name: '整改冒烟工作区', parentDirectory: ready.projectsDir }, name: '会话 A', model: 'kimi-coding/k2p7', domainId: 'com.transportx.workbench', profile };
    const created = await req('/api/conversations', input);
    assert.equal(created.status, 200, JSON.stringify(created));
    const a = created.data.conversation.id, ws = created.data.manifest.id;
    assert.equal((await req('/api/conversations', input)).data.conversation.id, a);
    assert.equal((await req('/api/health')).data.liveSessionCount, 0);
    assert.equal((await req(`/api/conversations/${a}/snapshot`)).data.runtime, null);
    const existing = { requestId: crypto.randomUUID(), workspace: { kind: 'existing', workspaceId: ws, expectedRevision: created.data.manifest.revision, defaultsRevision: created.data.manifest.defaultsRevision }, name: '会话 B' };
    assert.equal((await req('/api/conversations', { ...existing, requestId: crypto.randomUUID(), workspace: { ...existing.workspace, expectedRevision: 999 } })).status, 409);
    const second = await req('/api/conversations', existing);
    assert.equal(second.status, 200, JSON.stringify(second));
    const b = second.data.conversation.id;
    assert.equal(second.data.directory, created.data.directory);
    assert.equal((await req('/api/conversations', input)).data.conversation.id, a, 'dedup precedes revisions');
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1280, height: 900 } });
    const uiErrors = [];
    page.on('pageerror', e => uiErrors.push(String(e)));
    await page.goto(base, { waitUntil: 'networkidle' });
    await page.locator('.workspace-group-heading').filter({ hasText: '整改冒烟工作区' }).waitFor();
    await page.locator('.session-row').filter({ hasText: '会话 A' }).click();
    await page.getByRole('button', { name: '激活此会话', exact: true }).waitFor();
    assert.equal((await req('/api/health')).data.liveSessionCount, 0, 'history browsing never spawns Pi');
    await page.getByRole('button', { name: '激活此会话', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.conversation-offline-bar'));
    const activeA = (await req(`/api/conversations/${a}/snapshot`)).data.runtime.id;
    assert.equal((await req(`/api/workspaces/${ws}`)).data.conversations.find(item => item.record.id === a).lastConversationAt, null, 'activation does not manufacture message activity');
    assert.equal((await req(`/api/conversations/${a}/close`, { filePath: 'old-session.jsonl' })).status, 400, 'legacy path input is rejected even with a current protocol header');
    const composer = page.getByLabel('消息输入');
    await composer.fill('工作区会话测试');
    await page.getByRole('button', { name: '发送消息', exact: true }).click();
    await page.waitForTimeout(100);
    await page.locator('.session-row').filter({ hasText: '会话 B' }).click();
    await page.getByRole('button', { name: '激活此会话', exact: true }).waitFor();
    const occupied = await req(`/api/conversations/${b}/activate`, {});
    assert.equal(occupied.status, 409, JSON.stringify(occupied));
    assert.equal(occupied.data.code, 'workspace_busy');
    assert.equal((await req(`/api/conversations/${a}/snapshot`)).data.runtime.id, activeA);
    assert.equal((await req(`/api/conversations/${a}/close`, { stopCurrent: true })).status, 200);
    await page.getByRole('button', { name: '激活此会话', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.conversation-offline-bar'));
    const activeB = (await req(`/api/conversations/${b}/snapshot`)).data.runtime.id;
    assert.notEqual(activeB, activeA);
    assert.equal((await req(`/api/conversations/${b}/close`, { stopCurrent: true })).status, 200);
    assert.equal((await req('/api/health')).data.liveSessionCount, 0);
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('.session-row').filter({ hasText: '会话 A' }).click();
    await page.getByRole('button', { name: '激活此会话', exact: true }).waitFor();
    assert.equal((await req('/api/health')).data.liveSessionCount, 0);
    const independent = await req('/api/conversations', { ...input, requestId: crypto.randomUUID(), workspace: { kind: 'new', name: '独立运行工作区' }, name: '会话 C' });
    const c = independent.data.conversation.id;
    assert.equal((await req(`/api/conversations/${c}/activate`, {})).status, 200);
    await page.locator('.session-row').filter({ hasText: '会话 A' }).click();
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('.session-row.is-active').filter({ hasText: '会话 A' }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem('tau-active-conversation-id')), a, 'a newer running conversation cannot replace the saved selection before inventory arrives');
    assert.equal((await req('/api/health')).data.liveSessionCount, 1, 'restoring the offline A view does not activate it or stop C');
    const upload = new FormData();
    upload.append('files', new Blob(['road,flow\nA,12\n'], { type: 'text/csv' }), 'shared-source.csv');
    const uploadResponse = await fetch(base + `/api/conversations/${a}/attachments?source=picker`, { method: 'POST', headers: { 'X-TransportX-Protocol': '2' }, body: upload });
    assert.equal(uploadResponse.status, 200);
    const uploaded = (await uploadResponse.json()).attachments.find(item => item.name === 'shared-source.csv');
    assert.ok(uploaded);
    const library = (await req(`/api/conversations/${b}/attachments`)).data.attachments;
    assert.equal(library.find(item => item.id === uploaded.id).sourceConversationId, a, 'shared originals retain the uploading conversation');
    const original = await fetch(base + `/api/conversations/${b}/attachments/${uploaded.id}/file`);
    assert.equal(original.status, 200);
    assert.equal(await original.text(), 'road,flow\nA,12\n');
    assert.equal((await req('/api/health')).data.liveSessionCount, 1, 'offline file and attachment browsing leaves A/B stopped and C running');
    fs.writeFileSync(path.join(created.data.directory, 'shared.txt'), 'shared result');
    assert.equal((await req(`/api/conversations/${a}/files/content?path=shared.txt`)).status, 200);
    assert.equal((await req(`/api/conversations/${a}/files/content?path=.tau/workspace.json`)).status, 403);
    // A real Native history keeps its original bytes while proven old local file URLs use new addresses.
    const legacyReport = path.join(ready.resumeCwd, 'historical-report.txt'), legacyImage = path.join(ready.resumeCwd, 'historical-image.svg');
    fs.writeFileSync(legacyReport, 'Historical source opened through the new file API.');
    fs.writeFileSync(legacyImage, '<svg xmlns="http://www.w3.org/2000/svg" width="8" height="8"><rect width="8" height="8" fill="blue"/></svg>');
    const oldUrl = (file) => `http://127.0.0.1:3000/api/file/raw?${new URLSearchParams({ sessionId: 'untrusted-old-live', path: file, token: 'must-not-be-replayed' })}`;
    const reportUrl = oldUrl(legacyReport), imageUrl = oldUrl(legacyImage), privateUrl = oldUrl(path.join(ready.resumeCwd, '.tau/workspace.json')), foreignUrl = oldUrl(path.join(created.data.directory, 'shared.txt'));
    const previousRows = fs.readFileSync(ready.resumeFile, 'utf8').trim().split('\n').map(JSON.parse);
    fs.appendFileSync(ready.resumeFile, JSON.stringify({ type: 'message', id: crypto.randomUUID(), parentId: previousRows.filter((entry) => entry.id).at(-1).id, timestamp: new Date().toISOString(), message: { role: 'assistant', content: [{ type: 'text', text: `[历史报告](${reportUrl})\n\n![历史图像](${imageUrl})\n\n[私有元数据](${privateUrl}) [外部工作区](${foreignUrl}) [归属未知](http://localhost:3000/api/file/raw?path=report.txt&sessionId=unknown)` }], stopReason: 'stop', timestamp: Date.now() } }) + '\n');
    const nativeBytes = fs.readFileSync(ready.resumeFile);
    const legacyKey = path.relative(ready.sessionsDir, ready.resumeFile).replaceAll('\\', '/');
    const legacyRecord = (await req('/api/workspaces')).data.workspaces.flatMap((item) => item.conversations).find(({ record }) => record.history.key === legacyKey).record;
    const restored = (await req(`/api/conversations/${legacyRecord.id}/snapshot`)).data;
    assert.equal(restored.runtime, null);
    assert.equal(Object.keys(restored.resourceLinks).length, 2);
    assert.ok(!JSON.stringify(Object.values(restored.resourceLinks)).includes('must-not-be-replayed'));
    assert.equal(await (await fetch(base + restored.resourceLinks[reportUrl])).text(), 'Historical source opened through the new file API.');
    await page.evaluate((id) => localStorage.setItem('tau-active-conversation-id', id), legacyRecord.id);
    const legacyRequests = [];
    page.on('request', (request) => legacyRequests.push(new URL(request.url()).pathname));
    await page.reload({ waitUntil: 'networkidle' });
    const restoredLink = page.getByRole('link', { name: '历史报告', exact: true });
    await restoredLink.waitFor();
    await page.getByText('原计划缺失；激活前需确认当前配置', { exact: true }).waitFor();
    assert.ok((await restoredLink.getAttribute('href')).includes(`/api/conversations/${legacyRecord.id}/files/raw?`));
    await page.waitForFunction(() => { const image = document.querySelector('img[alt="历史图像"]'); return image?.complete && image.naturalWidth === 8; });
    assert.ok((await page.getByText('外部工作区 (旧资源链接不可用)', { exact: false }).count()) > 0);
    assert.equal(legacyRequests.filter((url) => /^\/api\/(live-sessions|sessions|session-history|file|files)(?:\/|$)/.test(url)).length, 0);
    assert.deepEqual(fs.readFileSync(ready.resumeFile), nativeBytes);
    assert.equal((await req('/api/health')).data.liveSessionCount, 1, 'historical links do not start the offline conversation or stop C');
    fs.mkdirSync('.plans/workspace-conversations', { recursive: true });
    fs.writeFileSync('.plans/workspace-conversations/historical-network.json', JSON.stringify({ verifiedFile: true, renderedImage: true, privateAndForeignAndUnboundRejected: true, nativeBytesPreserved: true, offlineDidNotStartPi: true, oldBusinessRequests: 0, paths: [...new Set(legacyRequests)].sort() }, null, 2));
    await page.screenshot({ path: '.plans/workspace-conversations/new-api-smoke.png', fullPage: true });
    const index = (await req('/api/workspaces')).data;
    const workspace = index.workspaces.find(v => v.id === ws);
    const deletion = await req(`/api/conversations/${b}`, { requestId: crypto.randomUUID(), expectedRevision: workspace.revision, confirm: true }, 'DELETE');
    assert.equal(deletion.status, 200, JSON.stringify(deletion));
    assert.equal(fs.readFileSync(path.join(created.data.directory, 'shared.txt'), 'utf8'), 'shared result');
    const fresh = (await req(`/api/workspaces/${ws}`)).data;
    const allDeletion = await req(`/api/workspaces/${ws}/delete`, { requestId: crypto.randomUUID(), expectedRevision: fresh.revision, confirm: true });
    assert.equal(allDeletion.status, 200, JSON.stringify(allDeletion));
    assert.equal(fs.existsSync(created.data.directory), false);
    assert.deepEqual(uiErrors, []);
    const socket = new WebSocket(base.replace('http', 'ws') + '/ws');
    const closed = new Promise(resolve => socket.once('close', code => resolve(code)));
    await new Promise(resolve => socket.once('open', resolve));
    socket.send(JSON.stringify({ type: 'hello', protocolVersion: 1 }));
    assert.equal(await closed, 4006);
    console.log('PASS: protocol fail-safe, durable creation/dedup, dual revisions, history-only browser open, explicit activation, busy refusal, stable identity, close/reload, scoped files and staged deletion');
}
catch (e) {
    console.error(log.slice(-10000));
    console.error(errors.slice(-10000));
    throw e;
}
finally {
    await browser?.close();
    host.kill('SIGTERM');
    await new Promise(r => host.exitCode !== null ? r() : host.once('exit', r));
    fs.rmSync(root, { recursive: true, force: true });
}
