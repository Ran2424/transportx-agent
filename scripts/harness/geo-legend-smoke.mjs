import assert from 'node:assert/strict';
import fs from 'node:fs';

export async function geoLegendSmoke(page, composer) {
  const directory = 'tmp/geo-legend-validation';
  fs.mkdirSync(directory, { recursive: true });
  await page.getByRole('button', { name: '发送消息', exact: true }).waitFor();
  await composer.fill('geo-legend-check'); await composer.press('Enter');
  await page.getByRole('tab', { name: '地图图例验收', exact: true }).waitFor();
  const panel = page.locator('.canvas-panel:not([hidden])');
  const stage = panel.locator('.geo-map-stage');
  const display = stage.getByRole('region', { name: '地图图例', exact: true });
  const expand = display.getByRole('button', { name: '展开图例', exact: true });
  await stage.locator('.maplibregl-canvas').waitFor();
  assert.equal(await expand.count(), 0, 'the component starts expanded');
  assert.equal(await display.getByText('拖动右下角调整宽度和高度', { exact: true }).count(), 0, 'the resize hint is removed');
  await stage.screenshot({ path: `${directory}/map-display-default.png` });
  assert.equal(await display.getByRole('tab').count(), 0);
  assert.equal(await display.getByRole('checkbox').count(), 0, 'reading has no persistent layer controls');
  assert.equal(await display.locator('details').count(), 0, 'reading has no layer tree');
  assert.equal(await display.getByText('常规图层', { exact: true }).count(), 0);
  assert.equal(await display.getByText('连续变化；范围外沿用端点样式', { exact: true }).count(), 0);
  assert.equal(await display.locator('[data-layer-id=labels]').count(), 0, 'plain name labels belong to settings');
  assert.equal(await display.evaluate(node => node.style.width), '');
  assert.equal(await display.evaluate(node => node.style.height), '');
  const metric = display.locator('.geo-legend-item[data-layer-id=sizes]');
  assert.equal(await metric.locator('.geo-legend-metric-title').count(), 1);
  await metric.getByText('点大小 · 连续', { exact: true }).waitFor();
  const steps = display.locator('.geo-legend-item[data-layer-id=steps]');
  await steps.getByText('颜色 · 分级', { exact: true }).waitFor();
  assert.deepEqual(await steps.locator('.geo-legend-entry > span').allTextContents(), ['< 100', '100 – < 300', '300 – < 500', '500 – < 1000', '1000 – < 2000', '≥ 2000']);
  const settingsButton = display.getByRole('button', { name: '图层设置', exact: true });
  await settingsButton.click();
  await stage.screenshot({ path: `${directory}/map-legend-settings.png` });
  assert.equal(await display.getByRole('checkbox').count(), 9, 'settings contain every layer exactly once');
  const route = display.getByRole('checkbox', { name: '线要素', exact: true });
  await route.uncheck(); await settingsButton.click();
  assert.equal(await display.locator('[data-layer-id=route]').count(), 0);
  await settingsButton.click(); await route.check();
  await display.locator('.geo-legend-settings').press('Escape');
  assert.equal(await display.getByRole('checkbox').count(), 0, 'Escape returns to reading');
  await settingsButton.evaluate(node => node.blur());

  const initial = await stage.boundingBox();
  const workspace = await panel.locator('.geo-workspace').boundingBox();
  assert.ok(initial.height > workspace.height * 0.7, 'the map receives the main workspace area');
  const natural = await display.boundingBox();
  assert.ok(natural.height > 320 && natural.height <= initial.height - 23, 'complete contents use the available map height rather than a preset panel height');
  await display.locator('.geo-legend-reading').evaluate(node => node.scrollTop = 0);
  await stage.screenshot({ path: `${directory}/map-display-auto.png` });
  const targetWidth = Math.min(360, initial.width - 24), targetHeight = 300;
  await page.mouse.move(natural.x + natural.width - 4, natural.y + natural.height - 4); await page.mouse.down();
  await page.mouse.move(natural.x + targetWidth - 4, natural.y + targetHeight - 4, { steps: 10 }); await page.mouse.up();
  const resized = await display.boundingBox();
  assert.ok(Math.abs(resized.width - targetWidth) < 5 && Math.abs(resized.height - targetHeight) < 5, 'the native resize grip changes both width and height');
  assert.equal(await display.locator('.geo-legend-reading').evaluate(node => node.scrollHeight > node.clientHeight), true, 'shrinking the panel scrolls complete contents instead of hiding items');
  const handle = display.getByRole('button', { name: /^移动图例/ });
  await handle.click();
  assert.equal(await expand.count(), 1, 'clicking the title collapses the panel');
  assert.equal(await stage.evaluate(node => node.clientHeight), Math.round(initial.height), 'collapse never resizes the map');
  assert.ok((await display.boundingBox()).width <= 136, 'collapsed display stays compact at the larger title size');
  assert.equal(await handle.locator('strong').evaluate((node) => node.scrollWidth <= node.clientWidth), true, 'the collapsed legend title remains readable');
  await handle.press('Enter');
  assert.ok(Math.abs((await display.boundingBox()).height - resized.height) < 2, 'collapse and expand preserve a manually chosen height');
  const start = await handle.boundingBox();
  const scaleBefore = await stage.locator('.maplibregl-ctrl-scale').innerText();
  assert.equal(await stage.locator('.maplibregl-ctrl-scale').evaluate((node) => getComputedStyle(node).fontSize), '12px');
  await page.mouse.move(start.x + 40, start.y + 15); await page.mouse.down();
  await page.mouse.move(start.x + 140, start.y + 95, { steps: 8 }); await page.mouse.up();
  assert.ok(await display.evaluate(node => node.offsetLeft > 70 && node.offsetTop > 50));
  assert.equal(await handle.getAttribute('aria-expanded'), 'true', 'a drag does not also toggle the panel');
  assert.equal(await stage.locator('.maplibregl-ctrl-scale').innerText(), scaleBefore);
  await handle.focus();
  const left = await display.evaluate(node => node.offsetLeft);
  await handle.press('ArrowRight');
  assert.equal(await display.evaluate(node => node.offsetLeft), left + 10);
  await handle.press('Home'); await handle.press('ArrowLeft');
  assert.equal(await display.evaluate(node => node.offsetLeft), 12);
  const dragStart = await handle.boundingBox();
  await page.mouse.move(dragStart.x + 30, dragStart.y + 15); await page.mouse.down();
  await page.mouse.move(initial.x + initial.width - 1, initial.y + initial.height - 1, { steps: 6 }); await page.mouse.up();
  assert.equal(await display.evaluate(node => { const a = node.getBoundingClientRect(), b = node.parentElement.getBoundingClientRect(); return a.right <= b.right - 11 && a.bottom <= b.bottom - 11; }), true);
  await handle.press('Home');
  const description = panel.locator('.geo-description');
  const collapsedHeight = await description.evaluate(node => node.clientHeight);
  await description.getByRole('button', { name: '展开说明', exact: true }).click();
  assert.ok(await description.evaluate(node => node.clientHeight) > collapsedHeight);
  await description.getByRole('button', { name: '收起说明', exact: true }).click();

  await settingsButton.click();
  const search = display.getByRole('searchbox', { name: '搜索图层' });
  await search.fill('参考区域');
  assert.equal(await display.locator('.geo-legend-control').count(), 1);
  await display.getByRole('checkbox', { name: '参考区域', exact: true }).check();
  await display.getByRole('checkbox', { name: '参考区域', exact: true }).uncheck();
  await search.fill('对象名称');
  assert.equal(await display.getByRole('checkbox', { name: '对象名称', exact: true }).count(), 1, 'settings search also finds plain label layers');
  await search.fill('');
  await settingsButton.click();
  await settingsButton.evaluate(node => node.blur());
  await display.locator('.geo-legend-reading').evaluate(node => node.scrollTop = 0);
  const originalTheme = await page.evaluate(() => document.documentElement.dataset.theme);
  for (const theme of ['light', 'dark', 'sand']) {
    await page.evaluate(value => document.documentElement.dataset.theme = value, theme);
    await stage.screenshot({ path: `${directory}/map-display-${theme}.png` });
    assert.equal(await display.evaluate(node => node.scrollWidth <= node.clientWidth), true);
  }
  await page.evaluate(value => document.documentElement.dataset.theme = value, originalTheme);
  const viewport = page.viewportSize();
  await page.setViewportSize({ width: 900, height: 900 });
  assert.equal(await display.evaluate(node => node.classList.contains('is-collapsed')), false, 'resizing the window preserves the expanded state');
  assert.equal(await panel.locator('.geo-toolbar').evaluate(node => node.scrollWidth <= node.clientWidth), true, 'map controls fit the narrower canvas');
  await stage.screenshot({ path: `${directory}/map-display-narrow.png` });
  await page.setViewportSize(viewport);
  if (await stage.locator('.maplibregl-ctrl-fullscreen').count()) {
    await stage.evaluate(node => { node.requestFullscreen = function () { window.__geoFullscreenTarget = this.className; return Promise.resolve(); }; });
    await stage.locator('.maplibregl-ctrl-fullscreen').click();
    assert.equal(await page.evaluate(() => window.__geoFullscreenTarget), 'geo-map-stage');
    await stage.evaluate(node => { node.requestFullscreen = undefined; node.webkitRequestFullscreen = undefined; document.exitFullscreen = undefined; document.webkitCancelFullScreen = undefined; });
    await stage.locator('.maplibregl-ctrl-fullscreen').click();
    await page.waitForFunction(() => document.querySelector('.geo-map-stage.maplibregl-pseudo-fullscreen'));
    assert.equal(await display.evaluate(node => node.closest('.maplibregl-pseudo-fullscreen') !== null), true);
    const fullscreenBox = await stage.boundingBox();
    assert.ok(fullscreenBox.width >= viewport.width - 1 && fullscreenBox.height >= viewport.height - 1);
    await stage.screenshot({ path: `${directory}/map-display-fullscreen.png` });
    await stage.locator('.maplibregl-ctrl-shrink').click();
    await stage.evaluate(node => { delete node.requestFullscreen; delete node.webkitRequestFullscreen; delete document.exitFullscreen; delete document.webkitCancelFullScreen; });
  }

  await page.setViewportSize({ width: viewport.width, height: 650 });
  await panel.getByRole('button', { name: '保存截图', exact: true }).click();
  await panel.getByRole('alert').filter({ hasText: '完整图例超出地图范围' }).waitFor();
  await page.setViewportSize(viewport);
  await settingsButton.click();
  for (const id of ['classes', 'steps', 'sizes', 'labels', 'chart']) await display.locator(`.geo-legend-control[data-layer-id=${id}] input`).uncheck();
  await search.fill('不存在的图层');
  await display.getByText('没有匹配的图层').waitFor();
  await handle.focus(); await handle.press('ArrowRight'); await handle.press('ArrowDown');
  await display.getByRole('button', { name: '收起图例', exact: true }).click();
  const request = page.waitForRequest(item => item.url().includes('/geo-screenshots'));
  await panel.getByRole('button', { name: '保存截图', exact: true }).click();
  const dataUrl = (await request).postDataJSON().dataUrl;
  fs.writeFileSync(`${directory}/map-display-export.png`, Buffer.from(dataUrl.split(',')[1], 'base64'));
  const dimensions = await page.evaluate(url => new Promise(resolve => { const image = new Image(); image.onload = () => resolve({ width: image.width, height: image.height }); image.src = url; }), dataUrl);
  const mapHeight = await stage.locator('.geo-map canvas').evaluate(node => node.height);
  assert.ok(dimensions.height < mapHeight + 220, 'only the full description is appended below the map');
  assert.equal(await stage.locator('.geo-map canvas').count(), 1);
  await expand.click(); await search.fill('');
  await settingsButton.click();
  await display.evaluate(node => { node.style.width = ''; node.style.height = ''; });
  await settingsButton.click();
  await display.getByRole('checkbox', { name: '连续区域', exact: true }).uncheck();
  await display.getByRole('checkbox', { name: '数值点位', exact: true }).check();
  await display.getByRole('checkbox', { name: '对象名称', exact: true }).check();
  await settingsButton.click();
  await handle.focus(); await handle.press('Home'); await handle.press('ArrowRight');
  const retainedLeft = await display.evaluate(node => node.offsetLeft);
  await handle.evaluate(node => node.blur());
  await settingsButton.evaluate(node => node.blur());
  await page.mouse.move(5, 5);
  await page.setViewportSize({ width: 1580, height: 1000 });
  await stage.screenshot({ path: `${directory}/map-display-compact.png` });
  await page.setViewportSize(viewport);
  await page.getByRole('button', { name: '发送消息', exact: true }).waitFor();
  await composer.fill('geo-legend-off'); await composer.press('Enter');
  await page.locator('.assistant-message', { hasText: '图例已关闭。' }).waitFor();
  assert.equal(await display.evaluate(node => node.offsetLeft), retainedLeft);
  assert.equal(await display.locator('canvas').count(), 0);
  assert.equal(await display.getByRole('checkbox', { name: '分类点位', exact: true }).count(), 1);
  await display.getByRole('checkbox', { name: '分类点位', exact: true }).check();
  const noLegendRequest = page.waitForRequest(item => item.url().includes('/geo-screenshots'));
  await panel.getByRole('button', { name: '保存截图', exact: true }).click();
  fs.writeFileSync(`${directory}/map-display-export-no-legend.png`, Buffer.from((await noLegendRequest).postDataJSON().dataUrl.split(',')[1], 'base64'));
  console.log('Legend reading/settings smoke: flat keys, secondary controls, exact classification, resize/scroll, drag, keyboard, themes, fullscreen and export passed.');
}
